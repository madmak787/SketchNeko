// Writes Apache/LiteSpeed config (Hostinger) into the static export after `next build`.
import { mkdirSync, writeFileSync } from "node:fs"
import { basePath } from "../next.config.mjs"

const root = `# Generated by scripts/write-htaccess.mjs — do not edit in out/
Options -Indexes
DirectoryIndex index.html
ErrorDocument 404 ${basePath}/404.html

<IfModule mod_headers.c>
  # Pages must always be revalidated so new deploys show up immediately
  <FilesMatch "\\.html$">
    Header set Cache-Control "no-cache"
  </FilesMatch>
</IfModule>

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css text/plain application/javascript application/json image/svg+xml
</IfModule>
`

// Build assets under _next/static have content hashes in their names, so they never change
const immutable = `# Generated by scripts/write-htaccess.mjs
<IfModule mod_headers.c>
  Header set Cache-Control "public, max-age=31536000, immutable"
</IfModule>
`

writeFileSync("out/.htaccess", root)
mkdirSync("out/_next/static", { recursive: true })
writeFileSync("out/_next/static/.htaccess", immutable)
console.log(`Wrote out/.htaccess (base path "${basePath}")`)
